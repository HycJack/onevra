// Command galleryicons builds the gallery-only catalog from checked-in accessors.
// Run with go generate ./examples/gallery/internal/gallery from the module root.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"regexp"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	file, err := parser.ParseFile(token.NewFileSet(), "../../../../icons/lucide/icons_gen.go", nil, parser.ParseComments)
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by galleryicons; DO NOT EDIT.\n\npackage gallery\n\nimport \"github.com/oneo-me/onevra/icons/lucide\"\n\nvar iconCatalog = []iconEntry{\n")
	pattern := regexp.MustCompile(`returns the Lucide ([a-z0-9-]+) icon\.`)
	for _, decl := range file.Decls {
		f, ok := decl.(*ast.FuncDecl)
		if !ok {
			continue
		}
		match := pattern.FindStringSubmatch(f.Doc.Text())
		if match == nil {
			return fmt.Errorf("missing icon name for %s", f.Name.Name)
		}
		fmt.Fprintf(&b, "{%q, lucide.%s},\n", match[1], f.Name.Name)
	}
	b.WriteString("}\n")
	code, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("icons_gen.go", code, 0644)
}
